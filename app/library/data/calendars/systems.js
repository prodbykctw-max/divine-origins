/** Get a calendar by id */
export function getCalendarById(id) {
  return CALENDAR_SYSTEMS.find(c => c.id === id) ?? null;
}

/** Get all calendars for a tradition */
export function getCalendarsByTradition(traditionId) {
  return CALENDAR_SYSTEMS.filter(c => c.tradition === traditionId);
}
