/** Get texts by tradition id */
export function getTextsByTradition(traditionId) {
  return SACRED_TEXTS.filter(t => t.tradition === traditionId);
}

/** Get a single text by id */
export function getTextById(id) {
  return SACRED_TEXTS.find(t => t.id === id) ?? null;
}

/** Get all texts sorted by date */
export function getTextsByDate() {
  return [...SACRED_TEXTS].sort((a, b) => a.dateSortKey - b.dateSortKey);
}
